    EN_GB("en-GB", "🇬🇧", "Inglês (UK)", "English (UK)");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.find { it.code.equals(code, ignoreCase = true) }
                ?: entries.find { it.code.take(2).equals(code.take(2), ignoreCase = true) }
                ?: PT_BR
    }
}

